from django.db import IntegrityError, transaction
from django.test import TestCase
from django.urls import reverse

from apps.accounts.models import User

from .models import (Skill, SkillCategory, SkillKind, SkillStatus, UserSkill)


class SkillModelTests(TestCase):
    def setUp(self):
        self.cat = SkillCategory.objects.create(name="Programming")

    def test_category_slug_autogenerated(self):
        self.assertEqual(self.cat.slug, "programming")

    def test_skill_slug_unique_across_same_name(self):
        other = SkillCategory.objects.create(name="Design")
        s1 = Skill.objects.create(name="Sketch", category=self.cat)
        s2 = Skill.objects.create(name="Sketch", category=other)  # same name, diff cat
        self.assertNotEqual(s1.slug, s2.slug)

    def test_duplicate_name_in_same_category_rejected(self):
        Skill.objects.create(name="Python", category=self.cat)
        with self.assertRaises(IntegrityError):
            with transaction.atomic():
                Skill.objects.create(name="Python", category=self.cat)

    def test_new_skill_defaults_to_pending(self):
        s = Skill.objects.create(name="Rust", category=self.cat)
        self.assertEqual(s.status, SkillStatus.PENDING)
        self.assertFalse(s.is_available)


class UserSkillConstraintTests(TestCase):
    def setUp(self):
        self.cat = SkillCategory.objects.create(name="Programming")
        self.skill = Skill.objects.create(
            name="Python", category=self.cat, status=SkillStatus.APPROVED
        )
        self.user = User.objects.create_user(email="u@example.com", password="pw-strong-123")

    def test_duplicate_user_skill_kind_rejected(self):
        UserSkill.objects.create(user=self.user, skill=self.skill, kind=SkillKind.OFFER)
        with self.assertRaises(IntegrityError):
            with transaction.atomic():
                UserSkill.objects.create(
                    user=self.user, skill=self.skill, kind=SkillKind.OFFER
                )

    def test_same_skill_different_kind_allowed(self):
        UserSkill.objects.create(user=self.user, skill=self.skill, kind=SkillKind.OFFER)
        UserSkill.objects.create(user=self.user, skill=self.skill, kind=SkillKind.WANT)
        self.assertEqual(self.user.user_skills.count(), 2)


class CatalogueAccessTests(TestCase):
    def test_catalogue_requires_authentication(self):
        resp = self.client.get(reverse("skill_catalogue"))
        self.assertEqual(resp.status_code, 302)
        self.assertIn(reverse("login"), resp.url)

    def test_only_approved_skills_appear(self):
        cat = SkillCategory.objects.create(name="Programming")
        Skill.objects.create(name="Python", category=cat, status=SkillStatus.APPROVED)
        Skill.objects.create(name="SecretLang", category=cat, status=SkillStatus.PENDING)
        user = User.objects.create_user(email="c@example.com", password="pw-strong-123")
        self.client.force_login(user)
        resp = self.client.get(reverse("skill_catalogue"))
        self.assertContains(resp, "Python")
        self.assertNotContains(resp, "SecretLang")


class SuggestionFlowTests(TestCase):
    def setUp(self):
        self.cat = SkillCategory.objects.create(name="Programming")
        self.user = User.objects.create_user(email="s@example.com", password="pw-strong-123")
        self.client.force_login(self.user)

    def test_suggestion_creates_pending_skill(self):
        resp = self.client.post(
            reverse("suggest_skill"),
            {"name": "Elixir", "category": self.cat.pk, "description": "FP language"},
        )
        self.assertEqual(resp.status_code, 200)
        skill = Skill.objects.get(name="Elixir")
        self.assertEqual(skill.status, SkillStatus.PENDING)
        self.assertEqual(skill.suggested_by, self.user)

    def test_suggested_skill_hidden_until_approved(self):
        skill = Skill.objects.create(
            name="Elixir", category=self.cat, status=SkillStatus.PENDING,
            suggested_by=self.user,
        )
        resp = self.client.get(reverse("skill_catalogue"))
        self.assertNotContains(resp, "Elixir")
        skill.status = SkillStatus.APPROVED
        skill.save()
        resp = self.client.get(reverse("skill_catalogue"))
        self.assertContains(resp, "Elixir")

    def test_duplicate_suggestion_rejected(self):
        Skill.objects.create(name="Elixir", category=self.cat)
        resp = self.client.post(
            reverse("suggest_skill"),
            {"name": "Elixir", "category": self.cat.pk, "description": ""},
        )
        self.assertEqual(resp.status_code, 200)
        self.assertEqual(Skill.objects.filter(name="Elixir").count(), 1)


class MySkillsTests(TestCase):
    def setUp(self):
        self.cat = SkillCategory.objects.create(name="Programming")
        self.skill = Skill.objects.create(
            name="Python", category=self.cat, status=SkillStatus.APPROVED
        )
        self.pending = Skill.objects.create(
            name="Pending", category=self.cat, status=SkillStatus.PENDING
        )
        self.a = User.objects.create_user(email="a@example.com", password="pw-strong-123")
        self.b = User.objects.create_user(email="b@example.com", password="pw-strong-123")

    def test_add_offer(self):
        self.client.force_login(self.a)
        resp = self.client.post(
            reverse("my_skills"),
            {"skill": self.skill.pk, "kind": SkillKind.OFFER,
             "proficiency": "advanced", "note": ""},
        )
        self.assertRedirects(resp, reverse("my_skills"))
        self.assertTrue(
            UserSkill.objects.filter(user=self.a, skill=self.skill, kind=SkillKind.OFFER).exists()
        )

    def test_pending_skill_not_selectable(self):
        self.client.force_login(self.a)
        from .forms import UserSkillForm
        form = UserSkillForm()
        ids = set(form.fields["skill"].queryset.values_list("pk", flat=True))
        self.assertIn(self.skill.pk, ids)
        self.assertNotIn(self.pending.pk, ids)

    def test_duplicate_add_shows_error(self):
        self.client.force_login(self.a)
        UserSkill.objects.create(user=self.a, skill=self.skill, kind=SkillKind.OFFER)
        resp = self.client.post(
            reverse("my_skills"),
            {"skill": self.skill.pk, "kind": SkillKind.OFFER, "proficiency": "", "note": ""},
        )
        self.assertEqual(resp.status_code, 200)
        self.assertEqual(
            UserSkill.objects.filter(user=self.a, skill=self.skill, kind=SkillKind.OFFER).count(), 1
        )

    def test_cannot_remove_another_users_skill(self):
        entry = UserSkill.objects.create(user=self.a, skill=self.skill, kind=SkillKind.OFFER)
        self.client.force_login(self.b)
        resp = self.client.post(reverse("remove_user_skill", args=[entry.pk]))
        self.assertEqual(resp.status_code, 404)
        self.assertTrue(UserSkill.objects.filter(pk=entry.pk).exists())
